function export_rtl(model, cfg, out_dir)
% EXPORT_RTL  Write rtl/gen/params.vh, wrom.mem and tree.mem from the SAME
%   cfg and model the golden model uses, so MATLAB and RTL cannot drift.
if nargin < 3, out_dir = fullfile(fileparts(mfilename('fullpath')), '..', 'rtl', 'gen'); end
if ~exist(out_dir, 'dir'), mkdir(out_dir); end
d = cfg.det; e = cfg.eng; c = model.cnn; r = cfg.rom;
% ---------------- params.vh ----------------
f = fopen(fullfile(out_dir, 'params.vh'), 'w');
fprintf(f, '// AUTO-GENERATED by matlab/export_rtl.m - do not edit.\n');
P = @(n, v) fprintf(f, 'localparam %-14s = %d;\n', n, v);
P('DET_TMIN', d.tmin); P('DET_TRACK', d.track); P('DET_REFR', d.refr);
P('DET_NPK_SH', d.npk_sh); P('DET_SPK_SH', d.spk_sh);
P('ENG_MIN_C', e.min_c); P('ENG_READY', e.ready); P('RR_MAX', e.rr_max); P('WAIT_T', e.wait); P('REF_BACK', e.ref_back);
P('SRCH_LO', e.srch_lo); P('SRCH_HI', e.srch_hi);
P('BASE_LO', e.base_lo); P('BASE_HI', e.base_hi);
P('SAT_LO', e.sat_lo); P('SAT_HI', e.sat_hi); P('SAT_TH', e.sat_th); P('FLAT_TH', e.flat_th);
P('W_SH', e.w_sh); P('ON_START', e.on_start); P('ON_MIN', e.on_min);
P('OFF_START', e.off_start); P('OFF_MAX', e.off_max);
P('P_A', e.p_a); P('P_B', e.p_b); P('T_A', e.t_a); P('T_LEN', e.t_len); P('T_MAX', e.t_max);
P('REF_SH_WARM', e.ref_sh_warm); P('REF_SH_RUN', e.ref_sh_run); P('REF_WARM_N', e.ref_warm_n);
P('TREE_DEPTH', cfg.tree.max_depth); P('TAU', model.tau);
P('CNN_S1', c.s1); P('CNN_S2', c.s2); P('CNN_S3', c.s3);
P('ROM_W1', r.w1); P('ROM_B1', r.b1); P('ROM_W2', r.w2); P('ROM_B2', r.b2);
P('ROM_WF1', r.wf1); P('ROM_BF1', r.bf1); P('ROM_WF2', r.wf2); P('ROM_BF2', r.bf2);
fclose(f);
% ---------------- weight ROM (16-bit words) ----------------
rom = zeros(r.len, 1);
chk = @(v, lo, hi, nm) assert(all(v(:) >= lo & v(:) <= hi & v(:) == round(v(:))), ['export_rtl: ' nm ' out of range']);
chk(c.w1, -8, 7, 'w1'); chk(c.w2, -8, 7, 'w2'); chk(c.wf1, -8, 7, 'wf1'); chk(c.wf2, -8, 7, 'wf2');
chk(c.b1, -32768, 32767, 'b1'); chk(c.b2, -32768, 32767, 'b2');
chk(c.bf1, -32768, 32767, 'bf1'); chk(c.bf2, -32768, 32767, 'bf2');
for oc = 1:8, for k = 1:3, rom(r.w1 + (oc-1)*3 + k) = c.w1(oc,k); end, end
rom(r.b1 + (1:8)) = c.b1(:);
for oc = 1:4, for ic = 1:4, for k = 1:3, rom(r.w2 + ((oc-1)*4 + ic - 1)*3 + k) = c.w2(oc,ic,k); end, end, end
rom(r.b2 + (1:4)) = c.b2(:);
for j = 1:16, for i = 1:40, rom(r.wf1 + (j-1)*40 + i) = c.wf1(j,i); end, end
rom(r.bf1 + (1:16)) = c.bf1(:);
for q = 1:3, for j = 1:16, rom(r.wf2 + (q-1)*16 + j) = c.wf2(q,j); end, end
rom(r.bf2 + (1:3)) = c.bf2(:);
f = fopen(fullfile(out_dir, 'wrom.mem'), 'w');
for i = 1:numel(rom), fprintf(f, '%04x\n', mod(rom(i), 65536)); end
fclose(f);
% ---------------- tree ROM (48-bit words) ----------------
T = model.tree; f = fopen(fullfile(out_dir, 'tree.mem'), 'w');
for i = 1:256
    w = T.leaf(i) * 2^41 + T.feat(i) * 2^37 + T.thr(i) * 2^26 + T.left(i) * 2^18 ...
        + T.right(i) * 2^10 + T.cls(i) * 2^8 + T.pur(i);
    assert(T.thr(i) >= 0 && T.thr(i) <= 2047 && T.feat(i) <= 15 && T.pur(i) <= 255 && T.left(i) <= 255 && T.right(i) <= 255);
    fprintf(f, '%012x\n', w);
end
fclose(f);
end
